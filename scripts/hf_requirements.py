"""Write the Gradio Space's requirements.txt from the locked dependencies.

    docker run --rm -v "$PWD:/w" -w /w ghcr.io/astral-sh/uv:0.8 export --frozen --no-dev \
        --no-hashes --no-emit-project --no-header -o build/requirements-locked.txt
    uv run python scripts/hf_requirements.py build/requirements-locked.txt

Same versions as uv.lock, with two exceptions forced by the Space:
- PyTorch: ZeroGPU supports 2.8-2.13, so the Space pins 2.13.0 (the default PyPI build, which
  also runs on CPU hardware) and lets pip pick the NVIDIA libraries that build needs.
- pydantic: the Space always installs gradio[mcp], which needs pydantic <= 2.12.5; pip picks
  the pydantic-core that version is tied to.
- pillow: gradio 6.31 needs pillow < 13, so the Space keeps 12.3.0, whose advisories (fixed
  in 13.0) concern image decoding; the demo decodes no images (email attachments are never
  opened). Lift this when gradio allows pillow 13.
Sentinel itself is not listed: the Space installs the requirements before its files are
copied in, so app.py imports it from src/ instead.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "deploy" / "huggingface" / "gradio" / "requirements.txt"
OVERRIDES = ["torch==2.13.0", "pydantic==2.12.5", "pillow==12.3.0", "spaces==0.51.3"]
DROP = re.compile(r"^(torch|nvidia-[a-z0-9-]+|triton|pydantic|pydantic-core|pillow)==", re.I)


def main(locked: Path) -> None:
    pins = [
        ln.strip()
        for ln in locked.read_text(encoding="utf-8").splitlines()
        if ln.strip() and not ln.lstrip().startswith("#") and not DROP.match(ln.strip())
    ]
    header = [
        "# Generated by scripts/hf_requirements.py from uv.lock; do not edit by hand.",
        "# Gradio itself is installed by the Space (sdk_version in README.md).",
    ]
    OUT.write_text("\n".join([*header, *OVERRIDES, *pins]) + "\n", encoding="utf-8")
    print(f"{OUT}: {len(pins) + len(OVERRIDES)} requirements")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
